// Assemble one standalone HTML file: inline CSS, inline viewer script, plan data.

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const read = (p) => readFileSync(join(here, p), 'utf8');

export const VERSION = JSON.parse(read('../package.json')).version;

export function renderHtml(plan, schedule, warnings = []) {
  const css = read('../assets/viewer.css');
  const js = read('../assets/viewer.js');
  // The browser reuses the same scheduler for what-if edits; strip module syntax to inline it.
  const unmodule = (src) => src.replace(/^import .*$/gm, '').replace(/^export /gm, '');
  const shared = ['./calendar.mjs', './schedule.mjs', './markdown.mjs'].map((f) => unmodule(read(f))).join('\n');
  const data = JSON.stringify({ generator: `planify ${VERSION}`, plan, schedule, warnings })
    .replace(/</g, '\\u003c')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029');
  const m = plan.meta;
  const esc = (s) => String(s ?? '').replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
  const lang = esc(m.locale || 'en');

  return `<!DOCTYPE html>
<html lang="${lang}" data-theme="light">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<meta name="generator" content="planify ${VERSION}">
<meta name="description" content="${esc(m.subtitle || (plan.overview && plan.overview.goal) || m.title)}">
<title>${esc(m.title)}</title>
<script>
(function () {
  var t = null;
  try { var q = new URLSearchParams(location.search).get('theme'); if (q === 'light' || q === 'dark') t = q; } catch (_) {}
  if (!t) { try { t = localStorage.getItem('planify-theme'); } catch (_) {} }
  if (t !== 'light' && t !== 'dark') t = matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light';
  document.documentElement.setAttribute('data-theme', t);
})();
</script>
<style id="planify-css">
${css}
</style>
</head>
<body>
<header class="top">
  <div class="top-inner">
    <div class="title-row">
      <div style="min-width:0">
        <h1>${esc(m.title)}</h1>
        ${m.subtitle ? `<p class="subtitle">${esc(m.subtitle)}</p>` : ''}
        <div class="meta-line" id="meta-line"></div>
      </div>
      <div class="tools">
        <div class="menu" id="export">
          <button class="btn" id="export-btn" aria-haspopup="true">⇩ <span class="label">Export</span></button>
          <div class="menu-list" role="menu">
            <button data-act="print">Print / PDF<small>All views, landscape</small></button>
            <button data-act="png">Roadmap PNG<small>2× image of the Gantt</small></button>
            <button data-act="svg">Roadmap SVG<small>Vector, for slides</small></button>
            <button data-act="copymd">Copy as Markdown<small>Paste into Confluence, Notion, Jira</small></button>
            <button data-act="md">Download Markdown</button>
            <button data-act="csv">Tasks CSV<small>Import into Excel, Jira, MS Project</small></button>
            <button data-act="json">Plan JSON<small>Source for edits and re-rendering</small></button>
          </div>
        </div>
        <button class="btn" id="theme" aria-label="Toggle theme"><span class="ico">☾</span></button>
      </div>
    </div>
    <nav class="tabs" id="tabs" aria-label="Views"></nav>
  </div>
  <div class="sim-bar" id="sim-bar" role="status" aria-live="polite" hidden></div>
</header>
<main>
  <section class="view" id="view-overview" data-title="Overview"></section>
  <section class="view" id="view-roadmap" data-title="Roadmap"></section>
  <section class="view" id="view-structure" data-title="Structure"></section>
  <section class="view" id="view-team" data-title="Team &amp; RACI"></section>
  <section class="view" id="view-risks" data-title="Risks"></section>
  <footer class="foot">
    <span>Generated by planify ${VERSION}</span>
    <span>Scheduled ${esc(schedule.today)} · ${schedule.calendar.workdays.length}-day work week${schedule.calendar.holidays.length ? ` · ${schedule.calendar.holidays.length} holidays` : ''}</span>
    ${m.evidence === 'illustrative' ? '<span>Illustrative: dates, people and amounts are placeholders until confirmed.</span>' : ''}
  </footer>
</main>
<aside class="drawer" id="drawer" aria-live="polite"></aside>
<script type="application/json" id="plan-data">${data}</script>
<script>
${shared}
${js}
</script>
</body>
</html>
`;
}
